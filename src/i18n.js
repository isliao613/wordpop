export const LANG_KEY = "wordpop-lang";

function readLang() {
  try {
    return localStorage.getItem(LANG_KEY) === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export let LANG = readLang();

export function setLang(l) {
  LANG = l === "en" ? "en" : "zh";
  try { localStorage.setItem(LANG_KEY, LANG); } catch { /* 無痕模式就不保存 */ }
}

