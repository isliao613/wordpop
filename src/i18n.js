/** t("中文") → 目前語言的字串 */
export function t(zh) {
  if (LANG !== "en") return zh;
  const v = EN[zh];
  return v === undefined ? zh : v;
}

/** tf("有 {0} 個", n) → 帶參數的字串 */
export function tf(zh, ...args) {
  return t(zh).replace(/\{(\d+)\}/g, (m, i) => {
    const v = args[Number(i)];
    return v === undefined ? m : String(v);
  });
}
